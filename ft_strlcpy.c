#include "libft.h"

int	ft_strlcpy(char *dest, const char *src, size_t n)
{
	int unsigned	i;

	i = 0;
	while (i < n && src[i] != '\0')
	{
		dest[i] = src[i];
		i++;
	}
	dest[i] = '\0';
	return (ft_strlen(src));
}
